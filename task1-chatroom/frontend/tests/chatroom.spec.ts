import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function enter(page: Page, nickname: string) {
  await page.goto('/')
  await page.getByLabel('怎么称呼你？').fill(nickname)
  await page.getByRole('button', { name: '进入工作空间' }).click()
  await expect(page.getByText('实时连接', { exact: true })).toBeVisible()
}
async function say(page: Page, text: string) {
  await page.getByLabel('聊天消息').fill(text)
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect(page.getByLabel('聊天消息')).toHaveValue('')
}

test('two browser clients: room, bot, tools, delegation, refresh persistence', async ({ browser }) => {
  const contextA = await browser.newContext({ viewport: { width: 1440, height: 960 } })
  const contextB = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  const a = await contextA.newPage(), b = await contextB.newPage()
  const errors: string[] = []
  for (const p of [a, b]) p.on('pageerror', e => errors.push(e.message))
  const suffix = Date.now().toString().slice(-7), roomName = `验收空间${suffix}`, botName = `数据助手${suffix}`, plannerName = `规划助手${suffix}`
  await enter(a, '林同学')
  await enter(b, '陈同学')
  await a.getByRole('button', { name: '创建聊天室', exact: true }).click()
  await a.getByLabel('房间名称', { exact: true }).fill(roomName)
  await a.getByLabel('房间描述（选填）').fill('真实双客户端与 AI 工具协作验收')
  await a.getByRole('dialog').getByRole('button', { name: '创建聊天室', exact: true }).click()
  await expect(a.getByRole('heading', { name: roomName, exact: true })).toBeVisible()
  await b.getByRole('navigation').getByRole('button', { name: roomName, exact: true }).click()
  await expect(b.getByRole('heading', { name: roomName, exact: true })).toBeVisible()
  await expect(a.getByText('2 人在线', { exact: true })).toBeVisible()
  await say(a, '你好，队友！这是一条真实广播消息。')
  await expect(b.getByTestId('chat-message').filter({ hasText: '你好，队友！这是一条真实广播消息。' })).toBeVisible()
  await say(b, '已实时收到，开始协作吧。')
  await expect(a.getByTestId('chat-message').filter({ hasText: '已实时收到，开始协作吧。' })).toBeVisible()

  await a.getByRole('button', { name: '创建 Bot', exact: true }).click()
  await a.getByLabel('Bot 名称', { exact: true }).fill(botName)
  await a.getByLabel('角色描述').fill('验收计算与时间工具')
  await a.getByLabel('System Prompt').fill('你是数据助手。计算必须调用 calculator，时间必须调用 get_current_time，使用中文。')
  await a.getByRole('button', { name: '创建并加入当前房间' }).click()
  await expect(a.getByRole('dialog')).toHaveCount(0)
  await expect(a.locator('.bot-card summary').getByText(botName, { exact: true })).toBeVisible()
  await a.getByRole('button', { name: '提及队友', exact: true }).click()
  await a.locator('.mention-menu').getByRole('button').filter({ hasText: botName }).click()
  await expect(a.getByLabel('聊天消息')).toHaveValue(`@${botName} `)
  await say(a, `@${botName} 计算 (128 + 256) * 3，现在时间是几点？`)
  const botReply = b.getByTestId('chat-message').filter({ hasText: '1152' })
  await expect(botReply).toBeVisible()
  await expect(botReply).toContainText('Demo / Mock')
  await a.getByRole('button', { name: '查看任务与工具记录' }).last().click()
  await expect(a.locator('.tool-record')).toHaveCount(2)
  await a.locator('.tool-record').filter({ hasText: 'calculator' }).locator('summary').click()
  await expect(a.locator('.tool-record').filter({ hasText: 'calculator' }).locator('.tool-body')).toContainText('1152')
  await a.locator('.detail-tabs').getByRole('button', { name: 'AI 队友' }).click()
  await a.getByRole('button', { name: '创建 Bot', exact: true }).click()
  await a.getByLabel('Bot 名称', { exact: true }).fill(plannerName)
  await a.getByLabel('角色描述').fill('规划任务并委派数据助手')
  await a.getByLabel('System Prompt').fill(`你是规划助手。请将计算委派给${botName}，根据其返回结果生成最终总结。`)
  await a.getByRole('dialog').getByRole('checkbox', { name: /Bot 任务委派/ }).check()
  await a.getByRole('button', { name: '创建并加入当前房间' }).click()
  await expect(a.getByRole('dialog')).toHaveCount(0)
  await expect(a.locator('.bot-card').filter({ hasText: plannerName })).toBeVisible()
  await say(a, `@${plannerName} 请委派给${botName}计算 99 * 12，并汇总结果`)
  const path = `${plannerName} → ${botName} → ${plannerName}`
  await expect(b.getByTestId('chat-message').filter({ hasText: path })).toContainText('1188')
  await a.getByRole('button', { name: '查看任务与工具记录' }).last().click()
  await expect(a.locator('.return-path')).toHaveText(path)
  await expect(a.locator('.chain-node')).toHaveCount(2)
  await a.reload()
  await expect(a.getByText('实时连接', { exact: true })).toBeVisible()
  await expect(a.getByTestId('chat-message').filter({ hasText: path })).toBeVisible()
  await expect(a.locator('.bot-card summary').getByText(botName, { exact: true })).toBeVisible()
  await a.getByRole('button', { name: '查看任务与工具记录' }).last().click()
  await expect(a.locator('.tool-record')).toHaveCount(2)
  await a.locator('.tool-record').first().locator('summary').click()
  await a.screenshot({ path: '../artifacts/desktop.png', fullPage: true })
  await b.screenshot({ path: '../artifacts/second-client.png', fullPage: true })
  expect(errors).toEqual([])
  await contextA.close(); await contextB.close()
})

